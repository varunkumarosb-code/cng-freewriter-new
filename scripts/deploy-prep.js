// scripts/deploy-prep.js
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

// 1. Generate IST Timestamp
const now = new Date();
const istOptions = {
  timeZone: 'Asia/Kolkata',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
  hour: '2-digit',
  minute: '2-digit',
  second: '2-digit',
  hour12: true
};
const istFormatted = new Intl.DateTimeFormat('en-IN', istOptions).format(now);

const pkg = JSON.parse(fs.readFileSync(path.join(rootDir, 'package.json'), 'utf-8'));
const version = `v${pkg.version || '2.0.0'}`;

const buildInfoContent = `// Auto-generated by scripts/deploy-prep.js
export const BUILD_INFO = {
  version: '${version}',
  deployedAtIST: '${istFormatted} IST',
  timestamp: ${now.getTime()},
  adminSecretDefault: 'WRITER_PANEL_LOGIN'
};
`;

fs.writeFileSync(path.join(rootDir, 'src', 'build-info.ts'), buildInfoContent, 'utf-8');
console.log(`✅ [1/3] Generated src/build-info.ts (${version} - ${istFormatted} IST)`);